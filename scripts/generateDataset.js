/**
 * ThermalMind Data Center Sensor Dataset Generator
 * Generates realistic historical and sample CSV datasets for ML training and data engineering demonstrations.
 */

const fs = require('fs');
const path = require('path');

const RACKS = [
  { id: 'RACK-A01', row: 'A', bay: 1, baseTemp: 22.5, coolingStatus: 'Optimal' },
  { id: 'RACK-A02', row: 'A', bay: 2, baseTemp: 24.0, coolingStatus: 'Optimal' },
  { id: 'RACK-B01', row: 'B', bay: 1, baseTemp: 23.0, coolingStatus: 'Optimal' },
  { id: 'RACK-B02', row: 'B', bay: 2, baseTemp: 26.5, coolingStatus: 'Warning' }, // High-density rack with thermal hotspot
];

const SERVERS_PER_RACK = 4;
const DC_ID = 'DC-EAST-01';

function getWorkloadCategory(cpu) {
  if (cpu < 20) return 'Idle';
  if (cpu < 50) return 'Low';
  if (cpu < 75) return 'Medium';
  if (cpu < 90) return 'High';
  return 'Critical';
}

function generateHistoricalDataset() {
  const records = [];
  const hours = 48;
  const intervalMinutes = 30; // 30-min interval = 96 timestamps per server
  const totalSteps = (hours * 60) / intervalMinutes;

  const now = new Date();
  const startTime = new Date(now.getTime() - hours * 60 * 60 * 1000);

  for (let step = 0; step < totalSteps; step++) {
    const timestamp = new Date(startTime.getTime() + step * intervalMinutes * 60 * 1000);
    const hourOfDay = timestamp.getHours();

    // Diurnal factor: higher load during 9am - 6pm (business hours)
    const businessHourFactor = (hourOfDay >= 9 && hourOfDay <= 18) ? 1.4 : 0.85;

    for (const rack of RACKS) {
      for (let s = 1; s <= SERVERS_PER_RACK; s++) {
        const srvId = `SRV-${rack.id.split('-')[1]}-0${s}`;

        // Base CPU utilization with server individual variation
        let cpu = Math.min(98, Math.max(8, (25 + (s * 7) + Math.sin(step / 6) * 15) * businessHourFactor + (Math.random() * 8 - 4)));
        cpu = Math.round(cpu * 10) / 10;

        // Base power (idle power ~130W, max power ~450W proportional to CPU)
        let powerWatts = Math.round(130 + (cpu / 100) * 310 + (Math.random() * 15 - 7));

        // Fan speed responds to CPU and Rack status
        let fanSpeed = Math.min(100, Math.max(30, Math.round(35 + (cpu * 0.45) + (rack.baseTemp > 25 ? 15 : 0))));

        // Temperature physics: base rack ambient + heat generated by power - heat dissipated by cooling
        let coolingEffect = (fanSpeed / 100) * 12.0;
        let heatingEffect = (powerWatts / 450) * 18.0;
        let temp = rack.baseTemp + heatingEffect - coolingEffect + (Math.random() * 0.8 - 0.4);

        // Inject deliberate thermal anomaly patterns for ML and Anomaly evaluation
        // Step 70 to 80 on RACK-B02 SRV-B02-03: CRAC damper failure causing gradual thermal buildup
        if (rack.id === 'RACK-B02' && srvId === 'SRV-B02-03' && step >= 70 && step <= 82) {
          temp += (step - 69) * 1.35; // rises up to 40°C+
          fanSpeed = 95; // fan maxes out but cooling fails to drop temp
        }

        // Step 40 on RACK-A02 SRV-A02-02: Sudden thermal spike
        if (rack.id === 'RACK-A02' && srvId === 'SRV-A02-02' && step >= 40 && step <= 44) {
          temp += 7.5;
        }

        temp = Math.round(temp * 10) / 10;
        let humidity = Math.round((46 + Math.cos(step / 8) * 5 + (Math.random() * 2 - 1)) * 10) / 10;

        let coolingStatus = rack.coolingStatus;
        if (temp > 38) coolingStatus = 'Critical';
        else if (temp > 32) coolingStatus = 'Warning';
        else if (temp > 28) coolingStatus = 'Active';

        records.push({
          timestamp: timestamp.toISOString(),
          dataCenterId: DC_ID,
          rackId: rack.id,
          serverId: srvId,
          temperature: temp,
          humidity: humidity,
          cpuUtilization: cpu,
          workload: getWorkloadCategory(cpu),
          powerWatts: powerWatts,
          coolingStatus: coolingStatus,
          fanSpeed: fanSpeed,
          dataSource: 'historical_import',
          validationStatus: 'VALID'
        });
      }
    }
  }

  return records;
}

function generateSampleUploadCsv() {
  const sampleRecords = [];
  const baseTime = new Date();

  for (let i = 0; i < 50; i++) {
    const timestamp = new Date(baseTime.getTime() - (50 - i) * 5 * 60 * 1000);
    const rackIdx = i % RACKS.length;
    const rack = RACKS[rackIdx];
    const srvNum = (i % 4) + 1;
    const srvId = `SRV-${rack.id.split('-')[1]}-0${srvNum}`;

    let cpu = Math.round((30 + Math.sin(i / 3) * 25 + Math.random() * 10) * 10) / 10;
    cpu = Math.min(99, Math.max(5, cpu));
    let powerWatts = Math.round(140 + (cpu / 100) * 290);
    let fanSpeed = Math.round(40 + (cpu * 0.4));
    let temp = Math.round((23 + (powerWatts / 450) * 14 - (fanSpeed / 100) * 9 + Math.random() * 1) * 10) / 10;

    // Introduce one suspect high reading for operator validation testing
    if (i === 42) {
      temp = 41.2;
      cpu = 88.5;
      fanSpeed = 98;
    }

    sampleRecords.push({
      timestamp: timestamp.toISOString(),
      dataCenterId: DC_ID,
      rackId: rack.id,
      serverId: srvId,
      temperature: temp,
      humidity: 48.5,
      cpuUtilization: cpu,
      workload: getWorkloadCategory(cpu),
      powerWatts: powerWatts,
      coolingStatus: temp > 35 ? 'Warning' : 'Optimal',
      fanSpeed: fanSpeed,
      dataSource: 'csv_upload',
      validationStatus: 'VALID'
    });
  }

  return sampleRecords;
}

function toCsv(records) {
  const headers = [
    'timestamp',
    'dataCenterId',
    'rackId',
    'serverId',
    'temperature',
    'humidity',
    'cpuUtilization',
    'workload',
    'powerWatts',
    'coolingStatus',
    'fanSpeed',
    'dataSource',
    'validationStatus'
  ];

  const rows = records.map(r => headers.map(h => r[h] !== undefined ? r[h] : '').join(','));
  return [headers.join(','), ...rows].join('\n');
}

function main() {
  const datasetsDir = path.resolve(__dirname, '../datasets');
  if (!fs.existsSync(datasetsDir)) {
    fs.mkdirSync(datasetsDir, { recursive: true });
  }

  console.log('Generating historical sensor dataset (48 hours, 1,500+ records)...');
  const historicalRecords = generateHistoricalDataset();
  const historicalCsvPath = path.join(datasetsDir, 'data_center_sensors_historical.csv');
  fs.writeFileSync(historicalCsvPath, toCsv(historicalRecords), 'utf8');
  console.log(`Saved historical dataset: ${historicalCsvPath} (${historicalRecords.length} records)`);

  console.log('Generating sample CSV for ingestion testing (50 records)...');
  const sampleRecords = generateSampleUploadCsv();
  const sampleCsvPath = path.join(datasetsDir, 'sample_upload.csv');
  fs.writeFileSync(sampleCsvPath, toCsv(sampleRecords), 'utf8');
  console.log(`Saved sample upload CSV: ${sampleCsvPath} (${sampleRecords.length} records)`);
}

main();
